
create table if not exists public.scout_source_registry (
  key text primary key,
  display_name text not null,
  source_type text not null check (source_type in ('platform','publication','newsletter','community','research','primary','analyst','standards','discovery')),
  discovery_role text not null default 'discovery' check (discovery_role in ('discovery','evidence','primary','research','community')),
  base_url text,
  active boolean not null default true,
  priority integer not null default 50 check (priority between 0 and 100),
  metadata jsonb not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.scout_source_registry enable row level security;

